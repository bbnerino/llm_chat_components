/**
 * 스트리밍 중인 마지막 블록의 "미완성 문법"을 임시로 보정한다.
 *
 * 토큰 단위로 그리면 이런 순간들이 화면에 그대로 노출된다:
 *   "```ts\nconst a"     → 닫히지 않은 펜스: 이후 전부가 코드로 보이거나, 펜스 문자가 그대로 보임
 *   "이건 **중요"        → 별표 두 개가 깜빡이다가 굵게 바뀜
 *   "[문서](https://ex" → 링크 문법이 반쯤 보였다가 사라짐
 *
 * 원칙: 보정은 렌더링 직전에만, 마지막 블록에만 한다. 원본 텍스트(상태)는 절대 건드리지 않는다.
 * 모호한 꼬리는 "추측해서 닫기"보다 "다음 토큰이 올 때까지 잠깐 숨기기"가 덜 깜빡인다.
 * (streamdown#539: 모호한 꼬리를 억지로 닫으면 오히려 스타일이 튀는 문제가 보고됨)
 */
export function repairMarkdownTail(block: string): string {
  let s = block

  // 1) 코드 펜스: 열린 개수가 홀수면 닫아준다. 펜스 안에서는 다른 보정을 하지 않는다.
  const fences = s.match(/^\s*(```|~~~)/gm)?.length ?? 0
  if (fences % 2 === 1) return s.endsWith('\n') ? `${s}\`\`\`` : `${s}\n\`\`\``

  // 2) 끝에 매달린 서식 문자는 숨긴다: "텍스트 *", "텍스트 **", "텍스트 `", "텍스트 ~~"
  s = s.replace(/[*_`~]+$/, '')

  // 3) 미완성 링크/이미지: "[텍스트", "[텍스트](https://ex" → 여는 괄호부터 숨긴다
  s = s.replace(/!?\[[^\]\n]*$/, '').replace(/!?\[[^\]\n]*\]\([^)\n]*$/, '')

  // 4) 짝이 안 맞는 굵게/인라인 코드는 닫는다 (이미 내용이 있으므로 닫는 게 자연스럽다)
  const line = s.slice(s.lastIndexOf('\n') + 1)
  if ((line.match(/\*\*/g)?.length ?? 0) % 2 === 1) s += '**'
  if ((line.replace(/\*\*/g, '').match(/`/g)?.length ?? 0) % 2 === 1) s += '`'

  // 5) 표: 헤더 구분선(|---|)이 오기 전에는 표로 해석되지 않아 파이프가 그대로 보인다 → 구분선 전까지 숨김
  if (/^\s*\|/.test(s) && !/^\s*\|?\s*:?-{3,}/m.test(s)) return ''

  return s
}
